namespace mp
{
    //////////////////////////////////////////////////////////////////////////////////////////////
    // Constructors	              															    //
    //////////////////////////////////////////////////////////////////////////////////////////////

    /////////////////////////////////////////////////////////////////////////////////////
    Answer::Answer()                                                                   //
    {
        
    }



    //////////////////////////////////////////////////////////////////////////////////////////////
    // Private constructors	    															    //
    //////////////////////////////////////////////////////////////////////////////////////////////

    /////////////////////////////////////////////////////////////////////////////////////
    Answer::Answer(Type type):                                                         //
    type(type)
    {
        error_message.clear();
    }


    /////////////////////////////////////////////////////////////////////////////////////
    Answer::Answer(std::string error_message):                                         //
    type(Error),
    error_message(error_message)
    {
        
    }



    //////////////////////////////////////////////////////////////////////////////////////////////
    // Method   	  																		    //
    //////////////////////////////////////////////////////////////////////////////////////////////

    /////////////////////////////////////////////////////////////////////////////////////
    bool Answer::IsSuccess()                                                           //
    {
        return type == Success ? true : false;
    }


    /////////////////////////////////////////////////////////////////////////////////////
    Answer::Type Answer::GetType()                                                     //
    {
        return type;
    }


    /////////////////////////////////////////////////////////////////////////////////////
    std::string Answer::GetErrorMessage()                                              //
    {
        return error_message;
    }


    /////////////////////////////////////////////////////////////////////////////////////
    void Answer::Clear()                                                               //
    {
        type = None;
        error_message.clear();
    }



    //////////////////////////////////////////////////////////////////////////////////////////////
    // Global operator overloading  														    //
    //////////////////////////////////////////////////////////////////////////////////////////////

    /////////////////////////////////////////////////////////////////////////////////////
    net::DataPacket& operator <<(net::DataPacket& packet, Answer answer)              //
    {
        packet << answer.type;

        if (answer.type == Answer::Error)
            packet << answer.error_message;

        return packet;
    }


    /////////////////////////////////////////////////////////////////////////////////////
    net::DataPacket& operator >>(net::DataPacket& packet, Answer& answer)              //
    {
        UINT32 _answer_type;
        packet >> _answer_type;
        answer.type = static_cast<Answer::Type>(_answer_type);

        if (answer.type == Answer::Error)
            packet >> answer.error_message;

        return packet;
    }

} // namespace mp